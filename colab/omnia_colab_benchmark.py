EPOCHS, BATCH, TILE, LEVEL = 4, 64, 256, 1

class SvsTiles(Dataset):
    """The status quo: openslide decodes JPEG-2000 during training, every epoch."""
    def __init__(self, path):
        self.path, self.s = path, None
        sl = openslide.OpenSlide(path)
        w, h = sl.level_dimensions[LEVEL]; self.ds = sl.level_downsamples[LEVEL]; sl.close()
        self.tx, self.ty = (w + TILE - 1)//TILE, (h + TILE - 1)//TILE
    def __len__(self): return self.tx * self.ty
    def __getitem__(self, i):
        # Handle opened lazily so it survives DataLoader worker forking.
        if self.s is None: self.s = openslide.OpenSlide(self.path)
        x = int((i % self.tx) * TILE * self.ds); y = int((i // self.tx) * TILE * self.ds)
        a = np.asarray(self.s.read_region((x, y), LEVEL, (TILE, TILE)).convert("RGB"))
        return torch.from_numpy(a.copy()).permute(2, 0, 1).float()/255.0, 0

def run(ds, label):
    m = resnet18(weights=None); m.fc = nn.Linear(512, 2); m = m.to(dev).train()
    opt = torch.optim.SGD(m.parameters(), lr=0.01); crit = nn.CrossEntropyLoss()
    dl = DataLoader(ds, batch_size=BATCH, shuffle=True, num_workers=0,
                    pin_memory=(dev.type == "cuda"))
    eps, dts = [], []
    for e in range(EPOCHS):
        if dev.type == "cuda": torch.cuda.synchronize()
        t0 = time.perf_counter(); data_t = 0.0; it = iter(dl)
        while True:
            td = time.perf_counter()
            try: x, y = next(it)
            except StopIteration: break
            data_t += time.perf_counter() - td
            x = x.to(dev, non_blocking=True); y = torch.as_tensor(y).to(dev)
            opt.zero_grad(); crit(m(x), y).backward(); opt.step()
        if dev.type == "cuda": torch.cuda.synchronize()
        tot = time.perf_counter() - t0
        eps.append(tot); dts.append(data_t)
        print(f"  {label} epoch {e+1}: {tot:7.2f}s   data {data_t:6.2f}s ({data_t/tot*100:5.1f}%)", flush=True)
    # Epoch 1 is discarded on both sides so neither is charged for warm-up.
    return float(np.mean(eps[1:])), float(np.mean(dts[1:])), eps[1:]

