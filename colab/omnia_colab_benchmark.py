"""
omnia-sdk benchmark — does the container actually speed up WSI training?

Self-contained: carries the SDK, fetches a public slide, and reports real
measurements. Run with:

    colab run --gpu T4 omnia_colab_benchmark.py

What it measures, and why it is built this way:

Data-loading speedup is a property of the container and will look large on any
machine. END-TO-END training speedup is capped by how much of your epoch was
data loading to begin with — Amdahl's law. A model-bound machine cannot show a
large end-to-end win no matter how fast the format is, so this script reports
the ceiling alongside the result rather than letting a small number look like a
failure of the container.

It also cross-checks itself: compute time is the same model on the same GPU on
both sides, so it must match. If it does not, the run is noise and the script
says so instead of reporting a speedup that will not reproduce.
"""
