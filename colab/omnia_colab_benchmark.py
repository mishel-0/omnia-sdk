# ─── 6. Report ────────────────────────────────────────────────────────────
# CUDA is asynchronous: forward/backward queue work and return immediately, so
# on the slow-data side the GPU drains its queue during the decode wait and the
# measured "compute" collapses toward zero. The per-epoch data/compute split is
# therefore not comparable across the two sides, and an Amdahl ceiling computed
# from it is wrong (it read 42x when the achievable figure was ~4x).
#
# The trustworthy quantities are the synchronised epoch totals and the compute
# floor measured on the fast-data side, where the CPU genuinely waits on the
# GPU. True ceiling = slow epoch / that floor.
compute_floor = om_ep - om_dt
share = svs_dt / svs_ep
ceiling = svs_ep / compute_floor if compute_floor > 0 else float("inf")
e2e = svs_ep / om_ep
dspeed = svs_dt / om_dt if om_dt > 0 else float("inf")
regime = "DATA-BOUND" if e2e >= 10 else ("MIXED" if e2e >= 2 else "MODEL-BOUND")
# Reliability is about run-to-run stability, not the CUDA-distorted split.
def _stable(xs):
    return (max(xs) - min(xs)) / max(xs) < 0.15 if xs else False
stable = _stable(svs_eps) and _stable(om_eps)

